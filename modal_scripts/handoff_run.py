"""
handoff_run.py - move a training run from one Modal workspace to the next.

Modal volumes are per-workspace with no cross-workspace copy, so continuing a run
elsewhere means pulling its checkpoint down to this PC and pushing it back up. Credit
runs out mid-run often enough that doing this by hand invites the one mistake that
matters: leaving a STALE checkpoint behind and silently resuming from the wrong step.
That has already cost this project once, on convnext_large.

    python modal_scripts/handoff_run.py <run> --from 16 --to 18

Pulls the run's checkpoints and logs from <from>, verifies what it got, creates
knee-runs on <to> if needed, and pushes them there. The source is left untouched.
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VOLUME = "knee-runs"
# what a resume actually needs: the rolling checkpoint, the best one, and the logs the
# engine appends to. Predictions are large and are regenerated by evaluate.py.
WANT = ["results/checkpoints/last.pt", "results/checkpoints/best.pt",
        "results/train_log.csv", "results/val_log.csv", "results/ud_ratio.csv",
        "results/training_summary.json"]


def env_for(session):
    e = dict(os.environ)
    e["MODAL_CONFIG_PATH"] = str(Path.home() / (".modal_session%d.toml" % session))
    e.pop("MSYS_NO_PATHCONV", None)          # the remote path must stay POSIX
    e["PYTHONIOENCODING"] = "utf-8"
    return e


def modal(session, *args, quiet=True):
    # bytes, not text: modal prints box-drawing characters and this PC's console codec
    # is cp1252, which raises on them mid-stream and would abort a half-finished handoff
    p = subprocess.run([sys.executable, "-m", "modal"] + list(args),
                       env=env_for(session), cwd=str(ROOT), capture_output=True)
    r = type("R", (), {"stdout": (p.stdout or b"").decode("utf-8", "replace"),
                       "stderr": (p.stderr or b"").decode("utf-8", "replace"),
                       "returncode": p.returncode})()
    if not quiet:
        print((r.stdout + r.stderr).strip()[-400:])
    return r


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run")
    ap.add_argument("--from", dest="src", type=int, required=True)
    ap.add_argument("--to", dest="dst", type=int, required=True)
    a = ap.parse_args()

    local = ROOT / "runs" / a.run
    print("=== pulling %s from session %d ===" % (a.run, a.src))
    got = []
    for rel in WANT:
        dest = local / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        r = modal(a.src, "volume", "get", VOLUME, "%s/%s" % (a.run, rel), str(dest), "--force")
        if dest.exists():
            got.append(rel)
            print("   %-42s %.1f MB" % (rel, dest.stat().st_size / 1e6))
        else:
            print("   %-42s absent on source" % rel)
    if not any(g.endswith(".pt") for g in got):
        raise SystemExit("no checkpoint pulled - nothing to hand off. Check the run name.")

    # say WHICH step is being carried over, so a stale file cannot pass unnoticed
    try:
        import torch
        ck = torch.load(local / "results/checkpoints/last.pt", map_location="cpu",
                        weights_only=False)
        print("   last.pt is epoch %s, step %s, score %s"
              % (ck.get("epoch"), ck.get("global_step"), ck.get("score")))
    except Exception as e:
        print("   (could not read last.pt: %s)" % e)

    print("\n=== pushing to session %d ===" % a.dst)
    modal(a.dst, "volume", "create", VOLUME)          # no-op if it already exists
    failed = []
    for rel in got:
        r = modal(a.dst, "volume", "put", VOLUME, str(local / rel),
                  "%s/%s" % (a.run, rel), "--force")
        # CHECK the result: an unverified push is how a hand-off silently loses a file and
        # the destination is discovered to be incomplete only after a container starts
        ok = r.returncode == 0 and "Error" not in (r.stdout + r.stderr)
        print("   %-42s %s" % (rel, "ok" if ok else "FAILED"))
        if not ok:
            failed.append(rel)
    if failed:
        raise SystemExit("push failed for: %s - the destination is INCOMPLETE, do not "
                         "launch there yet" % ", ".join(failed))

    r = modal(a.dst, "volume", "ls", VOLUME, "%s/results/checkpoints" % a.run)
    print("\ndestination now holds:")
    print(r.stdout or r.stderr)
    print("Set MODAL_CONFIG_PATH to session %d and rerun train.py; resume: last picks it up."
          % a.dst)


if __name__ == "__main__":
    main()
